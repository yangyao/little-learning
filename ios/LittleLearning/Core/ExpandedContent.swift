    static func toneAlternatives(_ reading: String) -> [String] {
        for group in ["āáǎàa","ēéěèe","īíǐìi","ōóǒòo","ūúǔùu","ǖǘǚǜü"] {
            for ch in group.prefix(4) where reading.contains(ch) {
                return group.prefix(4).filter { $0 != ch }.prefix(2).map { reading.replacingOccurrences(of:String(ch),with:String($0)) }
            }
        }
        for (plain,tones) in [("a",["ā","ǎ"]),("e",["ē","ě"]),("i",["ī","ǐ"]),("o",["ō","ǒ"]),("u",["ū","ǔ"])] where reading.contains(plain) {
            return tones.map { reading.replacingOccurrences(of:plain,with:$0) }
        }
        return ["mā","mǎ"]
    }
