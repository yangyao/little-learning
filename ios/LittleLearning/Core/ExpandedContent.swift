    static let clock: [ClockTask] = {
        var result: [ClockTask]=[]
        let oldSet=Set([180,540,390,15,705])
        for hour in 0..<12 { for minute in [0,15,30,45] {
            let target=hour*60+minute
            if !oldSet.contains(target) {
                result.append(.init(mode:.set,title:minute == 0 ? "认整点" : minute == 30 ? "认半点" : "认分钟",prompt:"把时钟拨到 \(ClockTask.text(target))",tip:"每一大格是 5 分，先选时针，再选分针。",start:0,target:target))
            }
        } }
        for hour in [1,4,7,10] { for minute in [5,10,20,25,35,40,50,55] {
            let target=hour*60+minute
            result.append(.init(mode:.set,title:"认五分刻度",prompt:"把时钟拨到 \(ClockTask.text(target))",tip:"分针每走一大格是 5 分。",start:0,target:target))
        } }
        for seconds in stride(from:0,through:55,by:5) where ![25,40].contains(seconds) {
            result.append(.init(mode:.seconds,title:"认秒针",prompt:"把秒针拨到 \(seconds) 秒",tip:"每个小刻度是 1 秒。",start:0,target:seconds))
        }
        let oldElapsed=Set(["500:535","650:675","480:580"])
        for start in [120,195,300,420,535,650] { for duration in [10,20,35,60] where start+duration < 720 {
            let target=start+duration
            if !oldElapsed.contains("\(start):\(target)") { result.append(.init(mode:.elapsed,title:"经过时间",prompt:"\(ClockTask.text(start))，再过 \(duration) 分是几点？",tip:"先加分钟，满 60 分就进 1 时。",start:start,target:target)) }
        } }
        return result
    }()
