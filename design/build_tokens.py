"""Resolve tokens.json and generate SwiftUI constants. Run from any directory."""
import json,re,pathlib
ROOT=pathlib.Path(__file__).resolve().parent

def resolve(value,root,chain=()):
    if isinstance(value,str) and re.fullmatch(r'\{[^{}]+\}',value):
        path=value[1:-1]
        if path in chain:raise ValueError('Circular token: '+path)
        v=root
        for key in path.split('.'):v=v[key]
        return resolve(v,root,chain+(path,))
    if isinstance(value,dict):return {k:resolve(v,root,chain) for k,v in value.items()}
    if isinstance(value,list):return [resolve(v,root,chain) for v in value]
    return value

def luminance(h):
    rgb=[int(h[i:i+2],16)/255 for i in (1,3,5)]
    rgb=[v/12.92 if v<=.04045 else ((v+.055)/1.055)**2.4 for v in rgb]
    return sum(a*b for a,b in zip(rgb,[.2126,.7152,.0722]))

def contrast(a,b):
    lo,hi=sorted([luminance(a),luminance(b)])
    return (hi+.05)/(lo+.05)

def generate():
    raw=json.loads((ROOT/'tokens.json').read_text());t=resolve(raw,raw)
    colors=t['semantic']['color'];motion=t['semantic']['motion']
    report=[]
    for pair in raw['contrastPairs']:
        v=resolve(pair,raw);ratio=contrast(v['foreground'],v['background'])
        assert ratio>=v['minimum'],(pair['name'],ratio)
        report.append({'name':pair['name'],'foreground':v['foreground'],'background':v['background'],'ratio':round(ratio,3),'minimum':v['minimum'],'pass':True})
    (ROOT/'contrast-report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
    (ROOT/'tokens.resolved.json').write_text(json.dumps(t,ensure_ascii=False,indent=2)+'\n')
    lines=['// Generated by design/build_tokens.py. Edit tokens.json, then regenerate.','import SwiftUI','','enum WoodlandTokens {','    enum Palette {']
    for name,value in colors.items():lines.append(f'        static let {name} = Color(rgb: 0x{value[1:]})')
    lines+=['    }']
    for swift,key in [('Spacing','spacing'),('Radius','radius'),('Size','size'),('Stroke','stroke')]:
        lines+=['    enum '+swift+' {']
        for name,value in t['semantic'][key].items():lines.append(f'        static let {name}: CGFloat = {value}')
        lines+=['    }']
    lines+=['    enum Motion {']
    for name,value in motion.items():lines.append(f'        static let {name}: Double = {value}')
    lines+=['    }','    struct TypeRole { let size: CGFloat; let lineHeight: CGFloat; let weight: Font.Weight; let textStyle: Font.TextStyle }','    enum Typography {']
    for name,v in t['semantic']['typography'].items():
        lines.append(f'        static let {name} = TypeRole(size: {v["size"]}, lineHeight: {v["lineHeight"]}, weight: .{v["swiftWeight"]}, textStyle: .{v["textStyle"]})')
    lines+=['    }','}','','private extension Color {','    init(rgb: UInt32) {','        self.init(.sRGB, red: Double((rgb >> 16) & 255) / 255, green: Double((rgb >> 8) & 255) / 255, blue: Double(rgb & 255) / 255, opacity: 1)','    }','}']
    lines+=['','// Primary-button reference only; other components follow DESIGN.md.','struct WoodenPrimaryButtonStyle: ButtonStyle {','    @Environment(\\.isEnabled) private var isEnabled','    @Environment(\\.accessibilityReduceMotion) private var reduceMotion','    func makeBody(configuration: Configuration) -> some View {','        let pressed = configuration.isPressed && isEnabled','        let shape = RoundedRectangle(cornerRadius: WoodlandTokens.Radius.control, style: .continuous)','        let face = isEnabled ? WoodlandTokens.Palette.actionPrimary : WoodlandTokens.Palette.disabledFill','        let ink = isEnabled ? WoodlandTokens.Palette.onPrimary : WoodlandTokens.Palette.disabledInk','        let side = isEnabled ? WoodlandTokens.Palette.actionPrimarySide : WoodlandTokens.Palette.disabledStroke','        let depth = WoodlandTokens.Motion.restDepth','        let travel = pressed ? WoodlandTokens.Motion.pressTravel : 0','        configuration.label','            .font(WoodlandTokens.Typography.label)','            .multilineTextAlignment(.center)','            .padding(.horizontal, WoodlandTokens.Spacing.lg)','            .padding(.vertical, WoodlandTokens.Spacing.md)','            .frame(maxWidth: .infinity, minHeight: WoodlandTokens.Size.touchMinimum)','            .foregroundStyle(ink)','            .background(shape.fill(face))','            .overlay(shape.strokeBorder(isEnabled ? Color.white.opacity(0.30) : WoodlandTokens.Palette.disabledStroke, lineWidth: WoodlandTokens.Stroke.hairline))','            .offset(y: reduceMotion ? 0 : travel)','            .background {','                shape.fill(side).offset(y: depth)','                    .shadow(color: WoodlandTokens.Palette.textPrimary.opacity(pressed ? 0.12 : 0.18), radius: pressed ? 2 : 8, x: 0, y: pressed ? 2 : 8)','            }','            .contentShape(shape)','            .animation(reduceMotion ? nil : .easeOut(duration: WoodlandTokens.Motion.pressDuration), value: pressed)','    }','}']
    # Keep native values sourced from the JSON material recipe.
    lines='\n'.join(lines)+'\n'
    lines=lines.replace('.font(WoodlandTokens.Typography.label)', '.modifier(WoodlandTextStyle(role: WoodlandTokens.Typography.label))')
    lines=lines.replace('.offset(y: reduceMotion ? 0 : travel)', '.offset(y: reduceMotion ? 0 : CGFloat(travel))').replace('shape.fill(side).offset(y: depth)', 'shape.fill(side).offset(y: CGFloat(depth))')
    lines+='''
// Scales the specified base size; do not replace with a fixed-size Font.
struct WoodlandTextStyle: ViewModifier {
    let role: WoodlandTokens.TypeRole
    @ScaledMetric private var pointSize: CGFloat
    @ScaledMetric private var extraLeading: CGFloat
    init(role: WoodlandTokens.TypeRole) {
        self.role = role
        _pointSize = ScaledMetric(wrappedValue: role.size, relativeTo: role.textStyle)
        _extraLeading = ScaledMetric(wrappedValue: max(0, role.lineHeight - role.size), relativeTo: role.textStyle)
    }
    func body(content: Content) -> some View {
        content.font(.system(size: pointSize, weight: role.weight, design: .rounded))
            .lineSpacing(extraLeading)
    }
}
'''
    lines=lines.replace('Color.white.opacity(0.30)',f'Color.white.opacity({t["semantic"]["material"]["highlightLeftAlpha"]})')
    # Shadow values are emitted as constants in this reference implementation.
    normal=t['semantic']['shadow']['raised'];pressed=t['semantic']['shadow']['pressed']
    lines=lines.replace('pressed ? 0.12 : 0.18',f'pressed ? {pressed["alpha"]} : {normal["alpha"]}').replace('radius: pressed ? 2 : 8',f'radius: pressed ? {pressed["swiftUIRadius"]} : {normal["swiftUIRadius"]}').replace('y: pressed ? 2 : 8',f'y: pressed ? {pressed["y"]} : {normal["y"]}')
    (ROOT/'swiftui').mkdir(exist_ok=True)
    (ROOT/'swiftui'/'WoodlandTokens.swift').write_text(lines)
    app_sources = ROOT.parent / 'ios' / 'LittleLearning' / 'Sources'
    if app_sources.is_dir():
        app_tokens = app_sources / 'WoodlandTokens.swift'
        if app_tokens.is_symlink(): app_tokens.unlink()
        app_tokens.write_text(lines)
    print(f'Validated references and {len(report)} contrast pairs; generated resolved tokens and SwiftUI source.')

if __name__=='__main__':generate()
